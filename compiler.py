from pathlib import Path
from typing import Iterable, Optional, TextIO
from xml.sax.saxutils import escape

from .ast import Program
from .parser import Parser
from .translator import Translator


class Compiler:
    """Compile GMAM source files into timeline XML."""

    def compile_sources(self, sources: Iterable[str]) -> dict[int, list[str]]:
        translator = Translator()
        declarations = []
        for source in sources:
            declarations.extend(Parser(source).parse().declarations)
        translator.translate(Program(declarations))
        return translator.timeline

    def compile_files(self, filenames: Iterable[str]) -> dict[int, list[str]]:
        return self.compile_sources(Path(filename).read_text(encoding="utf-8") for filename in filenames)

    @staticmethod
    def write_timeline(timeline: dict[int, list[str]], output: TextIO, format: str = "gms") -> None:
        if format == "gm82":
            Compiler.write_gm82(timeline, output)
            return
        if format == "gms":
            Compiler.write_gms(timeline, output)
            return
        raise ValueError(f"unsupported output format: {format}")
        

    @staticmethod
    def write_gms(timeline: dict[int, list[str]], output: TextIO) -> None:
        """Write the GameMaker Studio timeline XML format."""
        output.write("<!--This Document is generated by GameMaker, if you edit it by hand then you do so at your own risk!-->\n")
        output.write("<timeline>\n")
        for moment in sorted(timeline):
            for content in timeline[moment]:
                output.write("  <entry>\n")
                output.write(f"  <step>{moment}</step>\n")
                output.write("  <event>\n")
                output.write("  <action>\n")
                output.write("  <libid>1</libid>\n")
                output.write("  <id>603</id>\n")
                output.write("  <kind>7</kind>\n")
                output.write("  <userelative>0</userelative>\n")
                output.write("  <isquestion>0</isquestion>\n")
                output.write("  <useapplyto>-1</useapplyto>\n")
                output.write("  <exetype>2</exetype>\n")
                output.write("  <functionname></functionname>\n")
                output.write("  <codestring></codestring>\n")
                output.write("  <whoName>self</whoName>\n")
                output.write("  <relative>0</relative>\n")
                output.write("  <isnot>0</isnot>\n")
                output.write("  <arguments>\n")
                output.write("  <argument>\n")
                output.write("  <kind>1</kind>\n")
                output.write("  <string>\n")
                output.write(escape(content))
                output.write("</string>\n")
                output.write("  </argument>\n")
                output.write("  </arguments>\n")
                output.write("  </action>\n")
                output.write("  </event>\n")
                output.write("  </entry>\n")
        output.write("</timeline>\n")

    @staticmethod
    def write_gm82(timeline: dict[int, list[str]], output: TextIO) -> None:
        """Write the GM 8.2 action-script timeline format."""
        for moment in sorted(timeline):
            for content in timeline[moment]:
                output.write(f"#define {moment}\n")
                output.write("/*\"/*'/**//* YYD ACTION\n")
                output.write("lib_id=1\n")
                output.write("action_id=603\n")
                output.write("applies_to=self\n")
                output.write("*/\n")
                output.write(content)
                if content and not content.endswith("\n"):
                    output.write("\n")
